'use strict';

// Local update test of the Tauri build (TAURI-10, docs/TAURI_UPDATES.md; as Gustaf's updater-smoke.md): two
// ad-hoc-signed macOS bundles, 0.1.0 and 0.1.1, signed with a TEST key made here, and a loopback feed.
// Nothing touches the working checkout, GitHub, a tag, a release, or a real key.
//
//   node scripts/updater-smoke-tauri.js build <out>         key, then both bundles from an isolated copy of the sources
//   node scripts/updater-smoke-tauri.js serve <out>         the feed on http://127.0.0.1:47833/latest.json
//   node scripts/updater-smoke-tauri.js mode <out> <mode>   update | current | bad-signature | broken-download | offline
//   node scripts/updater-smoke-tauri.js run <out> <steps> [--keep]
//                                                         start a fresh copy of the 0.1.0 bundle (own profile and port),
//                                                         run `steps` (check | check,download | check,download,install),
//                                                         print its log; after an install, wait for the new version
//
// <out> must be OUTSIDE the repository (a scratch folder). The test key (<out>/keys) is generated by the Tauri CLI
// (`cargo tauri signer generate`; CAPRI_TAURI_CLI names cargo-tauri if it is not on PATH) with an empty password,
// is good for nothing but this test, and is never printed. HTTP on loopback is accepted only by a binary built here:
// CAPRI_LOCAL_UPDATER_TEST=1 at compile time AND `dangerousInsecureTransportProtocol` in its embedded
// configuration (updater.rs). Every other build takes https only.
// Needs the CLI and a Rust toolchain; macOS arm64/x64 only (the other systems are the CI's, TAURI-12).

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const { execFileSync, spawn, spawnSync } = require('node:child_process');
const { updaterConfig } = require('./updater-config');

const ROOT = path.resolve(__dirname, '..');
const PORT = 47833;
const PROFILE_PORT = 47834; // the app's hooks bridge
const VERSIONS = ['0.1.0', '0.1.1'];
const TEST_IDENTIFIER = 'capri.desktop.updatertest';
const MODES = ['update', 'current', 'bad-signature', 'broken-download', 'offline'];
const arch = process.arch === 'arm64' ? 'aarch64' : 'x86_64';
const PAYLOAD = `Capri-0.1.1-macOS-${arch === 'aarch64' ? 'arm64' : 'x64'}.app.tar.gz`;

function outside(out) {
  const abs = path.resolve(out);
  if (abs === ROOT || abs.startsWith(ROOT + path.sep)) throw new Error('<out> must be outside the repository');
  fs.mkdirSync(abs, { recursive: true });
  return abs;
}

function tauriCli() {
  return process.env.CAPRI_TAURI_CLI ? [process.env.CAPRI_TAURI_CLI, []] : ['cargo', ['tauri']];
}

function makeKey(out) {
  const dir = path.join(out, 'keys');
  const key = path.join(dir, 'capri-test.key');
  if (!fs.existsSync(key)) {
    fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
    const [bin, pre] = tauriCli();
    // output suppressed: it would show the private key
    execFileSync(bin, [...pre, 'signer', 'generate', '--ci', '-p', '', '-w', key], { stdio: 'ignore' });
    fs.chmodSync(key, 0o600);
  }
  return { key, publicKey: fs.readFileSync(`${key}.pub`, 'utf8').trim() };
}

// the files git knows of (committed or not, ignored ones left out), copied; heavy generated folders are not
function snapshot(out) {
  const dir = path.join(out, 'source');
  fs.rmSync(dir, { recursive: true, force: true });
  const files = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], { cwd: ROOT, encoding: 'utf8' })
    .split('\0').filter(Boolean);
  for (const file of files) {
    const from = path.join(ROOT, file);
    if (!fs.statSync(from, { throwIfNoEntry: false })?.isFile()) continue;
    fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    fs.copyFileSync(from, path.join(dir, file));
  }
  fs.symlinkSync(fs.realpathSync(path.join(ROOT, 'node_modules')), path.join(dir, 'node_modules'));
  return dir;
}

function build(out) {
  if (process.platform !== 'darwin') throw new Error('macOS only');
  const { key, publicKey } = makeKey(out);
  const source = snapshot(out);
  const run = (cmd, args, opts = {}) => {
    const r = spawnSync(cmd, args, { stdio: 'inherit', ...opts });
    if (r.status !== 0) throw new Error(`${cmd} ${args.slice(0, 3).join(' ')} failed (${r.status})`);
  };
  run(process.execPath, [path.join(source, 'scripts', 'stage-frontend.js')]);
  run(process.execPath, [path.join(source, 'scripts', 'build-sidecar.js')]);
  const [bin, pre] = tauriCli();
  const env = {
    ...process.env,
    CAPRI_LOCAL_UPDATER_TEST: '1',
    CARGO_TARGET_DIR: process.env.CARGO_TARGET_DIR || path.join(out, 'target'),
    TAURI_SIGNING_PRIVATE_KEY: key, // a path: the CLI reads the file
    TAURI_SIGNING_PRIVATE_KEY_PASSWORD: '',
  };
  for (const name of ['APPLE_SIGNING_IDENTITY', 'APPLE_ID', 'APPLE_PASSWORD', 'APPLE_TEAM_ID', 'APPLE_CERTIFICATE']) delete env[name];
  for (const version of VERSIONS) {
    const config = path.join(out, `config-${version}.json`);
    // another identifier: the single-instance lock is a socket named after it, so the test copy neither meets nor
    // disturbs an ordinary Capri that is running (its data folder is not used either: CAPRI_USER_DATA, `run`)
    fs.writeFileSync(config, JSON.stringify({ ...updaterConfig({ publicKey, local: { port: PORT }, version }), identifier: TEST_IDENTIFIER }));
    console.log(`[updater-smoke] building ${version}`);
    run(bin, [...pre, 'build', '--bundles', 'app', '--config', path.join(source, 'src-tauri', 'tauri.bundle.conf.json'), '--config', config], { cwd: path.join(source, 'src-tauri'), env });
    const bundle = path.join(env.CARGO_TARGET_DIR, 'release', 'bundle', 'macos');
    const dest = path.join(out, version);
    fs.rmSync(dest, { recursive: true, force: true });
    fs.mkdirSync(dest);
    execFileSync('ditto', [path.join(bundle, 'Capri.app'), path.join(dest, 'Capri.app')]);
    execFileSync('codesign', ['--verify', '--deep', '--strict', path.join(dest, 'Capri.app')]);
    if (version === VERSIONS[1]) {
      fs.copyFileSync(path.join(bundle, 'Capri.app.tar.gz'), path.join(out, PAYLOAD));
      fs.copyFileSync(path.join(bundle, 'Capri.app.tar.gz.sig'), path.join(out, `${PAYLOAD}.sig`));
    }
  }
  const signature = fs.readFileSync(path.join(out, `${PAYLOAD}.sig`), 'utf8').trim();
  const feed = {
    version: VERSIONS[1],
    notes: 'Local update test 0.1.0 -> 0.1.1.',
    pub_date: new Date().toISOString(),
    platforms: { [`darwin-${arch}`]: { signature, url: `http://127.0.0.1:${PORT}/${PAYLOAD}` } },
  };
  fs.writeFileSync(path.join(out, 'latest.json'), `${JSON.stringify(feed, null, 2)}\n`);
  fs.writeFileSync(path.join(out, 'mode.txt'), 'update');
  console.log(`[updater-smoke] ready: ${out}/{0.1.0,0.1.1}/Capri.app, feed ${PAYLOAD}`);
}

// the signature of the feed, spoiled: one bit of the minisign signature flipped (a base64 of base64 text)
function spoil(signature) {
  const lines = Buffer.from(signature, 'base64').toString().split('\n');
  const raw = Buffer.from(lines[1], 'base64');
  raw[10] ^= 1;
  lines[1] = raw.toString('base64');
  return Buffer.from(lines.join('\n')).toString('base64');
}

function serve(out) {
  const modeFile = path.join(out, 'mode.txt');
  const server = http.createServer((req, res) => {
    const route = req.url.split('?')[0];
    const mode = fs.readFileSync(modeFile, 'utf8').trim();
    console.log(`[feed] ${mode} ${req.method} ${route}`);
    if (route === '/latest.json') {
      if (mode === 'offline') { res.writeHead(503); return res.end('Simulated unavailable feed'); }
      const feed = JSON.parse(fs.readFileSync(path.join(out, 'latest.json'), 'utf8'));
      if (mode === 'current') feed.version = VERSIONS[0];
      if (mode === 'bad-signature') for (const t of Object.values(feed.platforms)) t.signature = spoil(t.signature);
      const body = JSON.stringify(feed);
      res.writeHead(200, { 'Content-Type': 'application/json', 'Cache-Control': 'no-store', 'Content-Length': Buffer.byteLength(body) });
      return res.end(body);
    }
    if (route === `/${PAYLOAD}`) {
      if (mode === 'broken-download') { res.writeHead(503); return res.end('Simulated download failure'); }
      const file = path.join(out, PAYLOAD);
      res.writeHead(200, { 'Content-Type': 'application/octet-stream', 'Content-Length': fs.statSync(file).size });
      return fs.createReadStream(file).pipe(res);
    }
    res.writeHead(404);
    res.end();
  });
  server.listen(PORT, '127.0.0.1', () => console.log(`[updater-smoke] feed: http://127.0.0.1:${PORT}/latest.json`));
}

// Starts a fresh copy of the 0.1.0 bundle (<out>/installed/Capri.app: the one an update replaces; never
// /Applications) with its own profile and port, and prints its log. After an install the old process hands
// over to the new one, which writes to the same pipe: `until` is then the line the NEW version prints.
function runApp(out, steps, { keep = false, wait = 90000, until } = {}) {
  const profile = path.join(out, 'profile');
  if (!keep) fs.rmSync(profile, { recursive: true, force: true });
  const installed = path.join(out, 'installed', 'Capri.app');
  if (!keep || !fs.existsSync(installed)) {
    fs.rmSync(path.dirname(installed), { recursive: true, force: true });
    fs.mkdirSync(path.dirname(installed));
    execFileSync('ditto', [path.join(out, VERSIONS[0], 'Capri.app'), installed]);
  }
  // the updater's own lines also go to a file: after an install the relaunched app does not write to our pipes
  const logFile = path.join(out, 'updater.log');
  fs.rmSync(logFile, { force: true });
  const child = spawn(path.join(installed, 'Contents', 'MacOS', 'capri'), [], {
    stdio: ['ignore', 'pipe', 'pipe'],
    env: { ...process.env, CAPRI_USER_DATA: profile, CAPRI_PORT: String(PROFILE_PORT), CAPRI_UPDATER_SMOKE_STEPS: steps, CAPRI_UPDATER_SMOKE_LOG: logFile },
  });
  const lines = [];
  let filePos = 0;
  const readFile = () => {
    try {
      const text = fs.readFileSync(logFile, 'utf8');
      for (const l of text.slice(filePos).split('\n')) if (l.trim()) { lines.push(l); console.log(`[updater.log] ${l}`); }
      filePos = text.length;
    } catch { /* not written yet */ }
  };
  const take = (chunk) => { for (const l of String(chunk).split('\n')) if (l.trim()) { lines.push(l); console.log(l); } };
  child.stdout.on('data', take);
  child.stderr.on('data', take);
  const seen = (re) => lines.some((l) => re.test(l));
  const settled = new Promise((resolve) => {
    const t0 = Date.now();
    const timer = setInterval(() => {
      readFile();
      if (seen(until) || Date.now() - t0 > wait) { clearInterval(timer); resolve(seen(until)); }
    }, 200);
  });
  // this copy's processes only (the relaunched ones are not our children): found by their path
  const stop = () => {
    child.kill();
    try {
      for (const line of execFileSync('ps', ['-axo', 'pid=,command=']).toString().split('\n')) {
        const m = line.trim().match(/^(\d+)\s+(.*)$/);
        if (m && m[2].startsWith(installed + path.sep)) process.kill(Number(m[1]));
      }
    } catch { /* gone already */ }
  };
  return { lines, seen, settled, stop, child, installed };
}

function usage() {
  console.error('usage: node scripts/updater-smoke-tauri.js build|serve <out> | mode <out> <mode> | run <out> <steps> [--keep]');
  process.exit(2);
}

module.exports = { spoil, runApp, MODES, PORT, PAYLOAD };

if (require.main === module) {
  const [action, outArg, arg] = process.argv.slice(2);
  if (!action || !outArg) usage();
  const out = outside(outArg);
  if (action === 'build') build(out);
  else if (action === 'serve') serve(out);
  else if (action === 'mode') {
    if (!MODES.includes(arg)) usage();
    fs.writeFileSync(path.join(out, 'mode.txt'), arg);
    console.log(`[updater-smoke] feed mode: ${arg}`);
  } else if (action === 'run') {
    const steps = arg || 'check';
    const last = steps.split(',').pop();
    // the line each plan ends on: the new version up and checked after an install
    const until = last === 'install' ? /update: current/ : last === 'download' ? /update: (downloaded|error)/ : /update: (current|available|error)/;
    const r = runApp(out, steps, { keep: process.argv.includes('--keep'), until: last === 'install' ? /update: (current|error)/ : until });
    r.settled.then((ok) => {
      r.stop();
      process.exit(ok ? 0 : 1);
    });
  } else usage();
}
