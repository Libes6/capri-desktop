'use strict';

// The contract between her pages and the Tauri shell (TAURI-11), read from the files: what the windows may do,
// which commands exist, and that the parity table (docs/TAURI_PARITY.md) is whole. No Rust needed here; the Rust
// side has its own `cargo test`.

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const read = (...p) => fs.readFileSync(path.join(root, ...p), 'utf8');
const json = (...p) => JSON.parse(read(...p));
const protocol = json('docs', 'protocol.json');

const BRIDGE_PERMISSIONS = ['allow-host-invoke', 'core:event:allow-listen', 'core:event:allow-unlisten'];

test('capabilities: exactly the overlay and the settings window, each with the bridge and nothing else', () => {
  const dir = path.join(root, 'src-tauri', 'capabilities');
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  assert.deepEqual(files, ['overlay.json', 'settings.json'], 'a new capability file needs its rights argued here');
  for (const f of files) {
    const cap = json('src-tauri', 'capabilities', f);
    const label = f.replace('.json', '');
    assert.equal(cap.identifier, label);
    assert.deepEqual(cap.windows, [label], 'named windows only, never a glob');
    assert.deepEqual([...cap.permissions].sort(), [...BRIDGE_PERMISSIONS].sort(), 'no window, shell, fs, dialog, opener or plugin right');
    assert.equal(cap.remote, undefined, 'no remote URL gets the bridge');
    assert.equal(cap.platforms, undefined);
  }
});

test('the one command: build.rs, the generated permission and the handler agree on host_invoke', () => {
  assert.match(read('src-tauri', 'build.rs'), /\.commands\(&\["host_invoke"\]\)/);
  const toml = read('src-tauri', 'permissions', 'autogenerated', 'host_invoke.toml');
  assert.deepEqual([...toml.matchAll(/commands\.(?:allow|deny) = \[([^\]]*)\]/g)].map((m) => m[1].trim()), ['"host_invoke"', '"host_invoke"']);
  const lib = read('src-tauri', 'src', 'lib.rs');
  assert.match(lib, /generate_handler!\[host_invoke\]/, 'her pages can call nothing else');
  assert.equal([...lib.matchAll(/#\[tauri::command\]/g)].length, 1);
  for (const f of fs.readdirSync(path.join(root, 'src-tauri', 'src'), { recursive: true })) {
    if (!String(f).endsWith('.rs') || f === 'lib.rs') continue;
    assert.ok(!/#\[tauri::command\]/.test(read('src-tauri', 'src', String(f))), `${f}: a second command would be callable by a window with the bridge`);
  }
  // the page can speak only for its own window
  assert.match(lib, /if scope != window\.label\(\)/);
});

test('windows: the labels Rust makes are the ones the capabilities and the core know, and a demo window has no rights', () => {
  const sources = fs.readdirSync(path.join(root, 'src-tauri', 'src'), { recursive: true }).filter((f) => String(f).endsWith('.rs'));
  const builders = [];
  for (const f of sources) {
    for (const m of read('src-tauri', 'src', String(f)).matchAll(/WebviewWindowBuilder::new\(\s*[^,]+,\s*([^,]+),/g)) builders.push(`${f}:${m[1].trim()}`);
  }
  assert.deepEqual(builders.sort(), ['demo.rs:&name', 'overlay.rs:LABEL', 'settings_window.rs:LABEL']);
  // the two scopes of the protocol are the two labels that have a capability
  const scopes = Array.isArray(protocol.scopes) ? protocol.scopes : Object.keys(protocol.scopes);
  assert.deepEqual([...scopes].sort(), ['overlay', 'settings']);
  // the demo terminal ("demo-<id>") is no one's label in a capability
  for (const f of fs.readdirSync(path.join(root, 'src-tauri', 'capabilities'))) {
    for (const w of json('src-tauri', 'capabilities', f).windows) assert.ok(!w.includes('*') && !w.startsWith('demo'), `${f} reaches the demo window`);
  }
  assert.match(read('src-tauri', 'src', 'demo.rs'), /on_navigation\(\|url\| url\.scheme\(\) == "data"\)/);
  assert.match(read('src-tauri', 'src', 'settings_window.rs'), /\.on_navigation\(allowed_url\)/);
});

test('tauri.conf: no window of its own, a strict CSP with no remote host and no eval', () => {
  const conf = json('src-tauri', 'tauri.conf.json');
  assert.deepEqual(conf.app.windows, [], 'every window is made by Rust, with its rights decided in code');
  const csp = conf.app.security.csp;
  assert.ok(!/unsafe-eval|unsafe-inline/.test(csp.replace(/style-src[^;]*unsafe-inline/, '')) || !/script-src[^;]*unsafe/.test(csp), 'no unsafe script');
  assert.ok(!/https?:\/\/(?!capri\.localhost|ipc\.localhost)/.test(csp), 'no remote host in the CSP');
  assert.match(csp, /default-src 'self'/);
  assert.equal(conf.app.security.dangerousDisableAssetCspModification, undefined);
});

test('every command and event of the protocol is in the parity table, and the table has no hole', () => {
  const doc = read('docs', 'TAURI_PARITY.md');
  for (const c of protocol.commands) {
    const key = c.scope === 'settings' ? `settings.${c.name}` : c.name;
    assert.ok(doc.includes(`\`${c.name}\``) || doc.includes(`\`${key}\``), `docs/TAURI_PARITY.md does not name the command ${c.name}`);
  }
  for (const e of protocol.events) assert.ok(doc.includes(`\`${e.name || e}\``), `docs/TAURI_PARITY.md does not name the event ${e.name || e}`);
  assert.ok(!/неизвестно|unknown|TBD|TODO/i.test(doc.replace(/`unknown`/g, '')), 'no unknown cell');
  // every table row of the parity tables has the seven columns and a status that means something
  const STATUS = /^(✅|🧪|⚠️|❌)/;
  let rows = 0;
  for (const line of doc.split('\n')) {
    if (!line.startsWith('|') || /^\|[\s:|-]+\|$/.test(line) || /^\| (Function|Command|Event|Gap)/.test(line)) continue;
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (cells.length !== 7) continue; // another kind of table (the gaps, the legend)
    rows++;
    assert.ok(cells.every(Boolean), `an empty cell: ${line.slice(0, 80)}`);
    assert.match(cells[5], STATUS, `status of "${cells[0]}"`);
  }
  assert.ok(rows >= 40, `the parity tables have ${rows} rows`);
});
